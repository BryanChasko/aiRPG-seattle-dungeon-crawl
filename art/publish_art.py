#!/usr/bin/env python3
"""Publish rendered art to S3 and write the placement notes the page owners work from.

Every image a plan renders goes to s3://bryanchasko.com/airpg-art/<class dir>/<file> (with its
sidecar), served at https://bryanchasko.com/airpg-art/<class dir>/<file>. The notes file,
docs/art-placements.md, lists for each image: the S3 key, the public URL, the page and spot it
belongs in, its alt text, a ready-to-paste markdown line, and whether the page already shows it.

Usage:
  python3 art/publish_art.py                 notes only (dry run, no upload)
  python3 art/publish_art.py --upload        upload every planned image that exists, then notes
  python3 art/publish_art.py --plan art/images/plans/<run>.json [--upload]   one plan only

Uploads use the AWS CLI with AWS_PROFILE (default aerospaceug-admin) in us-west-2.
The prefix airpg-art/ must stay registered as a sibling prefix in chasko-labs/bryan-chasko-com
(s3-prefix-registry.json) so the site deploy never deletes it.
"""
from __future__ import annotations
import argparse, json, os, subprocess, sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ART = Path(__file__).resolve().parent
BUCKET = "bryanchasko.com"
PREFIX = "airpg-art"
SITE = "https://bryanchasko.com"
NOTES = REPO_ROOT / "docs" / "art-placements.md"
PLANS = ART / "images" / "plans"


def key_for(out: str) -> str:
    p = Path(out)
    return f"{PREFIX}/{p.parent.name}/{p.name}"  # images/cards/x.webp -> airpg-art/cards/x.webp


def upload(local: Path, key: str) -> None:
    ctype = "image/webp" if local.suffix == ".webp" else "application/json"
    env = dict(os.environ, AWS_PROFILE=os.environ.get("AWS_PROFILE", "aerospaceug-admin"),
               AWS_DEFAULT_REGION=os.environ.get("AWS_DEFAULT_REGION", "us-west-2"))
    subprocess.run(["aws", "s3", "cp", str(local), f"s3://{BUCKET}/{key}", "--only-show-errors",
                    "--content-type", ctype, "--cache-control", "public, max-age=86400"], check=True, env=env)


def placed(page: str, file: str) -> bool:
    p = REPO_ROOT / page
    return p.exists() and file in p.read_text()


def rel_from(page: str, out: str) -> str:
    return os.path.relpath(ART / out, (REPO_ROOT / page).parent)


def clip_out(c: dict) -> str:
    stem = Path(c["source"]).name.split("-640x640")[0].split("-1200x675")[0].split("-96x96")[0].split(".")[0]
    stem = stem.removesuffix("-" + c["effect"])
    return f"images/motion/{stem}-{c['effect']}.webp"


def entries(plan_files: list[Path]):
    for pf in plan_files:
        plan = json.loads(pf.read_text())
        for r in plan.get("renders", []):
            yield plan["run"], r
        for c in plan.get("clips", []):  # images/plans/motion.json
            yield "motion", {"out": clip_out(c), "place": c.get("place", {}), "motion": True}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--plan", action="append", help="limit to these plan files")
    ap.add_argument("--upload", action="store_true")
    a = ap.parse_args()
    plan_files = [Path(p) for p in a.plan] if a.plan else sorted(PLANS.glob("20*.json")) + [PLANS / "motion.json"]
    rows, sent = [], 0
    for run, r in entries(plan_files):
        out = ART / r["out"]
        place = r.get("place", {})
        key = key_for(r["out"])
        exists = out.exists()
        if a.upload and exists:
            upload(out, key)
            for extra in (Path(str(out) + ".sidecar.json"), out.with_name(out.stem + "-still.webp")):
                if extra.exists():
                    upload(extra, key_for(str(extra.relative_to(ART))))
            sent += 1
        page = place.get("page", "")
        alt = place.get("alt", "")
        if not exists:
            status = "not rendered yet"
        elif place.get("replaces"):
            status = "replaces the file in place; no page edit"
        elif page and placed(page, out.name):
            status = "placed"
        else:
            status = "ready to place"
        if r.get("motion") and page:
            still = rel_from(page, r["out"].replace(".webp", "-still.webp"))
            snippet = (f'<picture><source srcset="{still}" media="(prefers-reduced-motion: reduce)">'
                       f'<img src="{rel_from(page, r["out"])}" alt="{alt}" width="240"></picture>')
        else:
            snippet = f"![{alt}]({rel_from(page, r['out'])})" if page else ""
        rows.append((run, out.name, key, page, place.get("where", ""), alt, snippet, status))

    lines = ["# Art placements",
             "",
             "Generated by `art/publish_art.py` from the plans in `art/images/plans/`. Do not edit by hand: change the plan's `place` field and rerun.",
             "",
             f"Every image is in the repo at the path in the snippet, and on S3 at `s3://{BUCKET}/<key>`, served at `{SITE}/<key>`. "
             "Pages in this repo link the repo path (it renders on GitHub); the site and other pages can use the URL.",
             "",
             "Status: `ready to place` means the page owner adds the snippet at the spot named; `placed` means the page shows it; "
             "`replaces` means a re-roll overwrote a file the pages already use.",
             ""]
    for run in dict.fromkeys(r[0] for r in rows):
        lines += [f"## {run}", "", "| image | page and spot | status |", "|---|---|---|"]
        for rr in (r for r in rows if r[0] == run):
            _, name, key, page, where, alt, snippet, status = rr
            lines.append(f"| [`{name}`]({SITE}/{key}) | `{page}`: {where} | {status} |")
        lines.append("")
        for rr in (r for r in rows if r[0] == run and r[7] == "ready to place"):
            _, name, key, page, where, alt, snippet, status = rr
            lines += [f"### `{name}` on `{page}`", "", f"Where: {where}.", "", f"S3: `s3://{BUCKET}/{key}`", "",
                      "```markdown", snippet, "```", ""]
    NOTES.write_text("\n".join(lines).rstrip() + "\n")
    print(f"{len(rows)} planned image(s), {sent} uploaded, notes in {NOTES.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
