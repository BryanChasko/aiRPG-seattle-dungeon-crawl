#!/usr/bin/env python3
"""Docs gate for the workshop: run before every docs commit.

Checks every tracked markdown page (README.md, workshop/, study/, docs/, web/public/):
  links      relative links and <img src> resolve on disk; #anchors exist in the target page
  external   http(s) links return 200 and their #anchors exist (skipped with --offline)
  vocabulary the banned words never appear (same pattern as the house grep)
  ascii      pages are plain ASCII, except fenced code blocks (trace trees, box drawings)
  pack       dungeon/study/knowledge-pack.md is current (dungeon/study/build_pack.py --check)

Usage:
  python3 dungeon/check_docs.py              everything
  python3 dungeon/check_docs.py --offline    skip the network check
Exit code 1 when any check fails. Standard library only.
"""
from __future__ import annotations
import argparse, re, subprocess, sys, urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ROOT = REPO_ROOT
BANNED = re.compile(r"m[a]ster|bible|chapter", re.I)  # bracket keeps this file out of its own grep
# generated by study/build_pack.py; its links keep workshop-relative paths for the study companion
NO_LINK_CHECK = {"dungeon/study/knowledge-pack.md"}


def pages() -> list[Path]:
    out = subprocess.run(["git", "ls-files", "*.md"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    extra = [p for p in (ROOT / "workshop").rglob("*.md")]  # new pages count before their first commit
    return sorted({ROOT / p for p in out} | set(extra))


def github_slug(heading: str) -> str:
    s = re.sub(r"[^a-z0-9 _-]", "", heading.strip().lower())
    return s.replace(" ", "-")


def anchors_of(path: Path) -> set[str]:
    found, counts = set(), {}
    for line in path.read_text().splitlines():
        m = re.match(r"^#{1,6} (.+)$", line)
        if m:
            slug = github_slug(m.group(1))
            n = counts.get(slug, 0)
            found.add(slug if n == 0 else f"{slug}-{n}")
            counts[slug] = n + 1
    return found


def prose_lines(text: str):
    fenced = False
    for i, line in enumerate(text.splitlines(), 1):
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if not fenced:
            yield i, line


def check(offline: bool) -> int:
    bad, external = [], {}
    all_pages = pages()
    for page in all_pages:
        rel = page.relative_to(ROOT)
        text = page.read_text()
        prose = "\n".join(line for _, line in prose_lines(text))  # links inside code fences are examples
        if str(rel) in NO_LINK_CHECK:
            prose = ""
        for link in re.findall(r"\]\(([^)\s]+)\)", prose):
            if link.startswith(("http://", "https://")):
                external.setdefault(link, rel)
                continue
            if link.startswith("mailto:"):
                continue
            path, _, frag = link.partition("#")
            target = (page.parent / path).resolve() if path else page.resolve()
            if not target.exists():
                bad.append(f"link   {rel}: missing {link}")
            elif frag and target.suffix == ".md" and frag not in anchors_of(target):
                bad.append(f"link   {rel}: no anchor #{frag} in {path or page.name}")
        for src in re.findall(r'<img src="([^"]+)"', prose):
            if not src.startswith("http") and not (page.parent / src).resolve().exists():
                bad.append(f"link   {rel}: missing image {src}")
        for i, line in enumerate(text.splitlines(), 1):
            if BANNED.search(line):
                bad.append(f"vocab  {rel}:{i}")
        for i, line in prose_lines(text):
            if any(ord(c) > 127 for c in line):
                bad.append(f"ascii  {rel}:{i}: {line.strip()[:60]}")
    if not offline:
        cache: dict[str, tuple] = {}
        for url, rel in sorted(external.items()):
            base, _, frag = url.partition("#")
            if base not in cache:
                try:
                    rq = urllib.request.Request(base, headers={"User-Agent": "Mozilla/5.0 link-check"})
                    with urllib.request.urlopen(rq, timeout=30) as r:
                        cache[base] = (r.status, r.read().decode("utf-8", "replace"))
                except Exception as e:  # report the failure, keep checking the rest
                    cache[base] = (getattr(e, "code", str(e)), "")
            status, body = cache[base]
            if status != 200:
                bad.append(f"extern {rel}: {status} {url}")
            elif frag and not any(s in body for s in (f'id="{frag}"', f"id={frag}", f'name="{frag}"')):
                bad.append(f"extern {rel}: anchor #{frag} not found in {base}")
    pack = subprocess.run([sys.executable, "dungeon/study/build_pack.py", "--check"], cwd=ROOT, capture_output=True, text=True)
    if pack.returncode:
        bad.append(f"pack   {(pack.stdout + pack.stderr).strip()}")
    print(f"{len(all_pages)} pages, {len(external)} external links{' (not fetched)' if offline else ''}")
    print("\n".join(bad) if bad else "docs gate: clean")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--offline", action="store_true")
    sys.exit(check(ap.parse_args().offline))
