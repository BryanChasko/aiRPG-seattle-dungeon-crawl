"""Build study/knowledge-pack.md: a compact copy of the crawl for a chat model's system prompt.

Per floor: the title, the objective, the SYSTEM DESIGN layer and every TODO step, word for word.
Then the cast sheets and the whole Crawl Handbook. About 30 KB, so it fits in one system prompt
with no retrieval. The companion site's "Ask the System AI" chat ships this file.

    python dungeon/study/build_pack.py          # rewrite the pack
    python dungeon/study/build_pack.py --check  # exit 1 if the pack is stale
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DUNGEON = REPO_ROOT / "dungeon"
PACK = DUNGEON / "study" / "knowledge-pack.md"
FLOORS = ["floor-0", "floor-1", "floor-2", "floor-3", "floor-4", "floor-5", "floor-6", "floor-7",
          "floor-8", "floor-8-1", "floor-8-2", "floor-8-3", "floor-8-4", "cleanup"]
FOLDER = {"floor-1": "dungeon/1_strands_basics", "floor-2": "dungeon/2_vended_tools", "floor-3": "dungeon/3_custom_tools",
          "floor-4": "dungeon/4_mcp_integration", "floor-5": "dungeon/5_a2a_integration", "floor-7": "dungeon/7_strands_harness",
          "floor-8": None, "floor-8-1": "dungeon/8_agentcore_production/diceserver",
          "floor-8-2": "dungeon/8_agentcore_production/characteragent", "floor-8-3": "dungeon/8_agentcore_production/rulesagent",
          "floor-8-4": "dungeon/8_agentcore_production/narrator"}
ICON = re.compile(r"<img [^>]*>\s*")


def section(text: str, heading: str) -> str:
    m = re.search(rf"^## {re.escape(heading)}\n(.*?)(?=^## |\Z)", text, flags=re.M | re.S)
    return m.group(1).strip() if m else ""


def system_design(text: str) -> str:
    m = re.search(r"\*\*SYSTEM DESIGN, LAYER [^*]+\*\*[^\n]*", text)
    return ICON.sub("", m.group(0)).strip() if m else ""


def todos(folder: str | None) -> list[str]:
    if not folder:
        return []
    out = []
    for path in sorted((REPO_ROOT / folder).rglob("*.py")):
        for line in path.read_text(encoding="utf-8").splitlines():
            if "# TODO:" in line:
                out.append(f"- {path.relative_to(REPO_ROOT).as_posix()}: {line.strip()[2:]}")
    return out


def build() -> str:
    head = subprocess.run(["git", "-C", str(REPO_ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    parts = [
        "# Seattle Strands Dungeon Crawl: knowledge pack",
        f"Generated by dungeon/study/build_pack.py from the workshop repository (main at {head or 'unknown'}). "
        "Source of truth: https://github.com/BryanChasko/aiRPG-seattle-dungeon-crawl",
        "",
    ]
    for name in FLOORS:
        text = (DUNGEON / "workshop" / f"{name}.md").read_text(encoding="utf-8")
        title = text.splitlines()[0].lstrip("# ").strip()
        parts.append(f"## {title} (dungeon/workshop/{name}.md)")
        objective = ICON.sub("", section(text, "Floor Objective")).split("\n\n", 1)[0]
        if objective:
            parts.append(objective)
        layer = system_design(text)
        if layer:
            parts.append(layer)
        steps = todos(FOLDER.get(name))
        if steps:
            parts.append("TODO steps:")
            parts.extend(steps)
        parts.append("")
    cast = (DUNGEON / "workshop" / "world" / "cast.md").read_text(encoding="utf-8")
    parts.append("## The party (dungeon/workshop/world/cast.md)")
    parts.append("Play as the party: Cordula Vance (she/her) and Barnaby (he/him) are the Crawlers; Shelly (he/him, geoduck) "
                 "and Chonks (he/him, spiny lumpsucker) are companions with no character sheet.")
    rows = re.findall(r"^\| (\d+) \| (\d+) \| (\d+) \| (\d+) \| (\d+) \| (\d+) \|$", cast, flags=re.M)
    for who, row in zip(("Cordula Vance, Human (Seattle Native) Amphibious Breacher", "Barnaby, Uplifted Giant Pacific Octopus Benthic Dragoon"), rows):
        parts.append(f"- {who}: strength {row[0]}, dexterity {row[1]}, constitution {row[2]}, "
                     f"intelligence {row[3]}, wisdom {row[4]}, charisma {row[5]}")
    parts.append("")
    parts.append("## The Crawl Handbook (dungeon/workshop/world/crawl-handbook/)")
    for path in sorted((DUNGEON / "workshop" / "world" / "crawl-handbook").glob("*.md")):
        parts.append(path.read_text(encoding="utf-8").strip().replace("\n# ", "\n### ").replace("# ", "### ", 1))
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def without_header(text: str) -> str:
    """The generator line carries the commit; staleness ignores it."""
    return "\n".join(line for line in text.splitlines() if not line.startswith("Generated by dungeon/study/build_pack.py"))


if __name__ == "__main__":
    fresh = build()
    if "--check" in sys.argv:
        current = PACK.read_text(encoding="utf-8") if PACK.exists() else ""
        if without_header(current) != without_header(fresh):
            sys.exit("study/knowledge-pack.md is stale: run python study/build_pack.py")
        print("knowledge pack is current")
    else:
        PACK.write_text(fresh, encoding="utf-8")
        print(f"wrote {PACK.relative_to(REPO_ROOT)} ({len(fresh.encode())} bytes)")
